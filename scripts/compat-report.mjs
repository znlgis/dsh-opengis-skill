#!/usr/bin/env node
/**
 * Generate "docs/compatibility.md" from really-executed contract tests.
 *
 * The package declares "dsh.compatibility" with evidence paths; this script is
 * what turns those claims into a dated, reproducible report. It runs each
 * evidence test in a fresh Node process with the TAP reporter, records the real
 * exit code, pass/fail/skip counts and elapsed time, and writes a Markdown table
 * carrying the generation time, script version, host facts and the DSH version
 * probed by diagnose().
 *
 * Honesty rules:
 * - a test file that does not exist, a process that cannot start, or a run whose
 *   cases were all skipped is written as "not-run" with the concrete reason;
 * - "pass" is only written when the process exited 0, reported zero failures and
 *   actually ran at least one case.
 *
 * Usage:
 *   node scripts/compat-report.mjs                    写 docs/compatibility.md
 *   node scripts/compat-report.mjs --out <path>       写到指定文件（测试用）
 *   node scripts/compat-report.mjs --json             stdout 额外输出 JSON 摘要
 *
 * Exit code: 1 when any suite is "fail", otherwise 0 ("not-run" is an honest
 * environment limitation, not a failure; the integration suite skips when no
 * Harness is installed).
 *
 * Zero dependencies; Node built-ins plus the package entry point.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { diagnose } from "../lib/index.js";

/** Repository root: this script lives in <root>/scripts/. */
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Version of this report format, surfaced in the generated document. */
const REPORT_VERSION = 1;

/** Marker the generated document carries; validate-skills.mjs requires it. */
const MARKER = "<!-- generated by npm run compat:report; do not edit by hand -->";

/** The evidence suites, in report order. */
const SUITES = [
	{
		file: "test/dsh-contract.test.mjs",
		label: "skill 注册表契约回归"
	},
	{
		file: "test/dsh-integration.test.mjs",
		label: "真实 DSH 注册表集成"
	}
];

/**
 * Read one "--name value" option.
 *
 * @param args - the CLI arguments.
 * @param name - the option name.
 * @returns the value, or undefined.
 */
function readOption(args, name) {
	const index = args.indexOf(name);
	return index === -1 ? undefined : args[index + 1];
}

/**
 * Parse the summary counters the TAP reporter prints at the end of a run.
 *
 * @param output - the child process stdout.
 * @returns the counters, defaulting to zero.
 */
function parseTap(output) {
	const counts = { tests: 0, pass: 0, fail: 0, cancelled: 0, skipped: 0, todo: 0 };
	for (const match of String(output ?? "").matchAll(/^# (tests|pass|fail|cancelled|skipped|todo) (\d+)$/gmu)) {
		counts[match[1]] = Number.parseInt(match[2], 10);
	}
	return counts;
}

/**
 * Run one evidence suite and classify the result.
 *
 * @param suite - the suite descriptor.
 * @returns the suite result the report renders.
 */
function runSuite(suite) {
	const file = join(root, suite.file);
	const command = "node --test --test-reporter=tap " + suite.file;
	if (!existsSync(file)) {
		return {
			...suite,
			command,
			status: "not-run",
			exitCode: null,
			counts: { tests: 0, pass: 0, fail: 0, cancelled: 0, skipped: 0, todo: 0 },
			durationMs: 0,
			reason: "测试文件不存在: " + suite.file
		};
	}
	// Run the evidence suite as a fresh top-level test run. The harness sets
	// NODE_TEST_CONTEXT for its own test children; inheriting it would make the
	// spawned runner report through the parent protocol instead of printing TAP,
	// which would look like an un-runnable suite.
	const env = { ...process.env };
	delete env.NODE_TEST_CONTEXT;
	const startedAt = Date.now();
	const result = spawnSync(process.execPath, ["--test", "--test-reporter=tap", file], {
		cwd: root,
		encoding: "utf8",
		timeout: 300_000,
		env
	});
	const durationMs = Date.now() - startedAt;
	const counts = parseTap(result.stdout);
	if (result.error !== undefined) {
		return {
			...suite,
			command,
			status: "not-run",
			exitCode: null,
			counts,
			durationMs,
			reason: "无法启动测试进程: " + String(result.error.code ?? result.error.message)
		};
	}
	if (result.signal !== null) {
		return { ...suite, command, status: "fail", exitCode: null, counts, durationMs, reason: "测试进程被信号终止: " + result.signal };
	}
	const exitCode = result.status;
	if (exitCode !== 0 || counts.fail > 0) {
		const tail = String(result.stderr ?? "").trim().split("\n").slice(-3).join(" / ");
		return {
			...suite,
			command,
			status: "fail",
			exitCode,
			counts,
			durationMs,
			reason: (counts.fail > 0 ? counts.fail + " 个用例失败" : "退出码 " + String(exitCode)) + (tail.length > 0 ? "：" + tail : "")
		};
	}
	if (counts.pass === 0 && counts.skipped > 0) {
		return {
			...suite,
			command,
			status: "not-run",
			exitCode,
			counts,
			durationMs,
			reason: "全部用例被跳过（未安装 DSH，或设置了 DSH_SKIP_INTEGRATION=1）"
		};
	}
	if (counts.tests === 0) {
		return { ...suite, command, status: "not-run", exitCode, counts, durationMs, reason: "没有执行任何用例" };
	}
	return { ...suite, command, status: "pass", exitCode, counts, durationMs, reason: "" };
}

/**
 * Render the Markdown report.
 *
 * @param report - the report data.
 * @returns the complete Markdown document.
 */
function renderMarkdown(report) {
	const tick = String.fromCharCode(96);
	const code = (value) => tick + value + tick;
	const lines = [
		MARKER,
		"# 兼容性验证报告",
		"",
		"本文件由 " + code("npm run compat:report") + " 从真实执行的契约测试生成，请勿手工编辑；重新生成即可刷新证据。",
		"",
		"## 环境",
		"",
		"| 项 | 值 |",
		"| --- | --- |",
		"| 生成时间 | " + report.generatedAt + "（UTC） |",
		"| 包版本 | " + code(report.packageVersion) + " |",
		"| 报告脚本版本 | " + String(report.scriptVersion) + "（" + code("scripts/compat-report.mjs") + "） |",
		"| Node | " + report.node + " |",
		"| 平台 | " + report.platform + " |",
		"| 本机 DSH 版本探测 | " + (report.hostVersionHint === null ? "未探测到" : code(report.hostVersionHint)) + " |",
		"",
		"## 证据",
		"",
		"| 测试文件 | 说明 | 命令 | 退出码 | 通过 | 失败 | 跳过 | 耗时 | 判定 |",
		"| --- | --- | --- | --- | --- | --- | --- | --- | --- |"
	];
	for (const suite of report.suites) {
		lines.push(
			"| " +
				code(suite.file) +
				" | " +
				suite.label +
				" | " +
				code(suite.command) +
				" | " +
				(suite.exitCode === null ? "—" : String(suite.exitCode)) +
				" | " +
				String(suite.counts.pass) +
				" | " +
				String(suite.counts.fail) +
				" | " +
				String(suite.counts.skipped) +
				" | " +
				String(suite.durationMs) +
				" ms | " +
				suite.status +
				" |"
		);
	}
	lines.push("", "## 判定口径", "");
	lines.push("- " + code("pass") + "：退出码 0、失败数 0，且至少执行了一个用例；");
	lines.push("- " + code("fail") + "：退出码非 0、存在失败用例，或测试进程被信号终止；");
	lines.push(
		"- " +
			code("not-run") +
			"：测试文件缺失、测试进程无法启动，或全部用例被跳过。原因写在各行的备注里，" +
			code("not-run") +
			" 绝不记成 " +
			code("pass") +
			"。"
	);
	const notes = report.suites.filter((suite) => suite.status !== "pass");
	if (notes.length > 0) {
		lines.push("", "## 未全部通过的原因", "");
		for (const suite of notes) lines.push("- " + code(suite.file) + "（" + suite.status + "）：" + suite.reason);
	}
	const passed = report.suites.filter((suite) => suite.status === "pass").length;
	lines.push(
		"",
		"## 汇总",
		"",
		"共 " + String(report.suites.length) + " 个证据套件：" + String(passed) + " 个 pass，" + String(report.suites.length - passed) + " 个未 pass。",
		""
	);
	return lines.join("\n");
}

const args = process.argv.slice(2);
const json = args.includes("--json");
const out = resolve(readOption(args, "--out") ?? join(root, "docs", "compatibility.md"));
const host = diagnose();

const report = {
	generatedAt: new Date().toISOString(),
	scriptVersion: REPORT_VERSION,
	packageVersion: host.packageVersion,
	hostVersionHint: host.hostVersionHint,
	node: process.version,
	platform: process.platform + " " + process.arch,
	suites: SUITES.map(runSuite)
};

try {
	mkdirSync(dirname(out), { recursive: true });
	writeFileSync(out, renderMarkdown(report) + "\n", "utf8");
	if (!json) console.log("compat-report: wrote " + out);
} catch (cause) {
	console.error("compat-report: cannot write " + out + ": " + (cause instanceof Error ? cause.message : String(cause)));
	process.exitCode = 1;
}

if (json) {
	// Machine-readable mode: the JSON is the only stdout payload so a caller can
	// parse the whole stream without stripping progress lines.
	console.log(JSON.stringify(report, null, 2));
} else {
	for (const suite of report.suites) console.log("  " + suite.file + ": " + suite.status + (suite.reason.length > 0 ? " (" + suite.reason + ")" : ""));
}
if (report.suites.some((suite) => suite.status === "fail")) process.exitCode = 1;
